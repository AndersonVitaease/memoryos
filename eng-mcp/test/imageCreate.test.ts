test("credential resolution: env wins over file, file works alone, none fails closed — values never logged", async () => {
  const dir = await mkdtemp(join(tmpdir(), "imagecreate-test-"));
  const file = join(dir, "cred.json");
  await writeFile(file, JSON.stringify({ apiToken: "file-token-value", accountId: "file-account" }), "utf8");
  try {
    const fromEnv = await resolveGenerationCredential({ env: { CLOUDFLARE_API_TOKEN: "env-token", CLOUDFLARE_ACCOUNT_ID: "env-account" } });
    assert.equal(fromEnv?.accountId, "env-account");
    const fromFile = await resolveGenerationCredential({ env: {}, file });
    assert.equal(fromFile?.accountId, "file-account");
    assert.equal(fromFile?.apiToken, "file-token-value");
    const none = await resolveGenerationCredential({ env: {}, file: join(dir, "missing.json") });
    assert.equal(none, null);
    const badJson = await resolveGenerationCredential({ env: {}, file: join(tmpdir(), "imagecreate-test-does-not-exist") });
    assert.equal(badJson, null);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test("asset delivery route: GET serves staged bytes, TTL expiry 404s, non-asset requests pass through", () => {
  const id = putGeneratedAsset(Buffer.from("hello-bytes"), "image/jpeg", 1000);
  const hit = serveImageAsset("GET", `${IMAGE_ASSET_PATH_PREFIX}${id}`, 2000);
  assert.equal(hit.handled, true);
  if (hit.handled) {
    assert.equal(hit.status, 200);
    assert.equal(hit.contentType, "image/jpeg");
    assert.deepEqual(hit.bytes, Buffer.from("hello-bytes"));
  }
  const unknown = serveImageAsset("GET", `${IMAGE_ASSET_PATH_PREFIX}nope`, 2000);
  assert.equal(unknown.handled, true);
  assert.ok(unknown.handled && unknown.status === 404);
  assert.equal(serveImageAsset("POST", `${IMAGE_ASSET_PATH_PREFIX}${id}`, 2000).handled, false);
  assert.equal(serveImageAsset("GET", "/mcp", 2000).handled, false);
  assert.equal(serveImageAsset("GET", "/", 2000).handled, false);
  const beyondTtl = 1000 + 16 * 60_000; // 16 min > the 15-minute asset TTL
  const expired = serveImageAsset("GET", `${IMAGE_ASSET_PATH_PREFIX}${id}`, beyondTtl);
  assert.ok(expired.handled && expired.status === 404); // the expiry lookup itself sweeps the expired asset
  const second = putGeneratedAsset(Buffer.from("a"), "image/jpeg", beyondTtl);
  const third = putGeneratedAsset(Buffer.from("b"), "image/jpeg", beyondTtl);
  assert.notEqual(second, third);
  assert.equal(imageAssetCount(beyondTtl + 1), 2); // only the two fresh assets remain
  assert.equal(imageAssetCount(beyondTtl + 16 * 60_000), 0); // both expired and swept
});

