type EditRule = { when: (input: ImageEditInput) => boolean; code?: string; message?: string; result?: Record<string, unknown> };
function fakeEdit(rules: EditRule[] = []) {
  const calls: ImageEditInput[] = [];
  const edit = async (input: ImageEditInput) => {
    calls.push(input);
    const rule = rules.find((candidate) => candidate.when(input));
    if (!rule) return { status: "ok", action: input.action, applied: [], changed: true };
    if (rule.code) return { status: "error", action: input.action, code: rule.code, message: rule.message ?? "executor rejected" };
    return { status: "ok", action: input.action, ...(rule.result ?? {}) };
  };
  return { calls, edit };
}
function fakeGenerate(model = "@cf/black-forest-labs/flux-1-schnell") {
  const calls: GenerationRequest[] = [];
  const generate = async (request: GenerationRequest) => {
    calls.push(request);
    return { bytes: Buffer.alloc(256, 7), contentType: "image/jpeg", model };
  };
  return { calls, generate };
}
function baseDeps(generate: ReturnType<typeof fakeGenerate>["generate"], edit: ReturnType<typeof fakeEdit>["edit"]) {
  return { generate, edit, putAsset: () => "asset-1", publicBaseUrl: "https://mcp.test" };
}
const isOpenDocument = (input: ImageEditInput) => input.action === "document" && input.document?.op === "open";
const isExport = (input: ImageEditInput) => input.action === "export";

test("schema: strict — raw execution channels are structurally impossible", () => {
  const base = { action: "compose", canvas: { width: 1024, height: 1024 }, elements: [{ type: "text", text: "x" }] };
  for (const key of ["script", "toolName", "jsonrpc", "shell", "command", "url", "steps", "tool", "rawArgs"]) {
    const candidate = { ...base, [key]: "inject" } as unknown as Record<string, unknown>;
    assert.equal(imageCreateInputSchema.safeParse(candidate).success, false, `key ${key} must be rejected`);
  }
  assert.equal(imageCreateInputSchema.safeParse({ action: "nonsense" }).success, false);
});

test("schema: minimal payload for each of the 7 high-level actions parses", () => {
  for (const action of ["generate", "background", "scene", "product", "campaign", "compose", "variation"] as const) {
    assert.equal(imageCreateInputSchema.safeParse({ action }).success, true, action);
  }
  assert.equal(imageCreateInputSchema.safeParse({ action: "generate", prompt: "x", outputPath: "C:/a.png", width: 1024, height: 1024, model: "flux-1-schnell", count: 2 }).success, true);
});

test("generate: happy path stages the generated asset over HTTPS and exports locally, with no secrets and no blobs in the result", async () => {
  const gen = fakeGenerate();
  const { calls, edit } = fakeEdit();
  const result = await runImageCreate("engineering.image.create", { action: "generate", prompt: "a red apple on white", outputPath: "C:/tmp/art.png" }, baseDeps(gen.generate, edit));
  assert.equal(result.status, "ok");
  assert.equal(gen.calls.length, 1);
  assert.equal(calls.length, 2);
  assert.equal(calls[0].action, "document");
  assert.equal(calls[0].document?.op, "open");
  assert.equal(calls[0].document?.path, "https://mcp.test/image-asset/asset-1");
  assert.equal(calls[1].action, "export");
  assert.equal(calls[1].output?.path, "C:/tmp/art.png");
  assert.equal(calls[1].output?.overwrite, true);
  const outputs = result.outputs as Array<Record<string, unknown>>;
  assert.equal(outputs.length, 1);
  assert.equal(outputs[0].ok, true);
  assert.equal(outputs[0].path, "C:/tmp/art.png");
  const serialized = JSON.stringify(result);
  assert.ok(!serialized.includes("apiToken"));
  assert.ok(!serialized.includes("Bearer"));
  assert.ok(!serialized.includes("BwcHBw")); // no base64 blob of the generated bytes may leak into the result
  const ops = result.operationsApplied as string[];
  assert.ok(ops.some((op) => op.startsWith("generate:")));
  assert.ok(ops.includes("open:generated-asset"));
  assert.ok(ops.includes("export:png"));
});

