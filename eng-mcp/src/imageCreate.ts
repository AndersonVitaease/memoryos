export type ImageCreateInput = z.infer<typeof imageCreateInputSchema>;
type OutputFormat = "png" | "jpg" | "jpeg" | "webp";
const OUTPUT_FORMATS: readonly OutputFormat[] = ["png", "jpg", "jpeg", "webp"];
type ElementInput = NonNullable<ImageEditInput["elements"]>[number];
type ComposeElementInput = z.infer<typeof composeElement>;
type PlacementInput = z.infer<typeof placement>;

export type ImageCreateDeps = {
  credentialLoader?: () => Promise<ImageCreateCredential | null>;
  generate?: (request: GenerationRequest) => Promise<GenerationResult>;
  edit?: (input: ImageEditInput) => Promise<Record<string, unknown>>;
  putAsset?: (bytes: Buffer, contentType: string) => string;
  publicBaseUrl?: string;
};

const RELAY_CODES = new Set(["LOCAL_RELAY_DISABLED", "LOCAL_EDITOR_OFFLINE", "RELAY_TIMEOUT", "RELAY_INVALID_RESPONSE", "RELAY_DISCONNECTED"]);
type EditOutcome = { ok: true; result: Record<string, unknown> } | { ok: false; code: string; message: string };
async function editStep(deps: ImageCreateDeps, input: ImageEditInput, step: string): Promise<EditOutcome> {
  const edit = deps.edit ?? ((candidate: ImageEditInput) => runImageEdit(candidate));
  const result = await edit(input);
  if (result.status === "ok") return { ok: true, result };
  const code = typeof result.code === "string" ? result.code : "EXECUTOR_ERROR";
  const message = typeof result.message === "string" ? result.message : "executor rejected the request";
  return { ok: false, code, message: `${step}: ${code}: ${message}` };
}
function mapEditFailure(step: string, failure: { code: string; message: string }, assetPaths: string[] = []): ImageCreateError {
  if (RELAY_CODES.has(failure.code)) return new ImageCreateError(failure.code, failure.message);
  if (assetPaths.some((assetPath) => assetPath.length > 0 && failure.message.includes(assetPath))) return new ImageCreateError("INPUT_ASSET_NOT_FOUND", failure.message);
  if (step === "export") return new ImageCreateError("EXPORT_FAILED", failure.message);
  if (step.startsWith("open-input:") || step.startsWith("place-input:")) return new ImageCreateError("INPUT_ASSET_NOT_FOUND", failure.message);
  return new ImageCreateError("COMPOSITION_FAILED", failure.message);
}
function exportOf(result: Record<string, unknown>): Record<string, unknown> | null {
  const output = result.output;
  return typeof output === "object" && output !== null ? output as Record<string, unknown> : null;
}

function outputFormatOf(outputPath: string): OutputFormat | null {
  const match = /\.([a-z0-9]+)$/i.exec(outputPath.trim());
  if (!match) return null;
  const ext = match[1].toLowerCase();
  return (OUTPUT_FORMATS as readonly string[]).includes(ext) ? ext as OutputFormat : null;
}
function withOutputIndex(outputPath: string, index: number): string {
  const match = /^(.*?)(\.[a-z0-9]+)?$/i.exec(outputPath.trim());
  const stem = match && match[2] ? match[1] : outputPath.trim();
  const ext = match && match[2] ? match[2] : "";
  return `${stem}-${index}${ext || ".png"}`;
}
function providerBackgroundSize(canvas: { width: number; height: number }): { width: number; height: number } {
  const snap = (value: number) => Math.max(256, Math.min(1024, Math.round(value / 8) * 8));
  if (canvas.width >= 256 && canvas.width <= 1024 && canvas.height >= 256 && canvas.height <= 1024 && canvas.width % 8 === 0 && canvas.height % 8 === 0)
    return { width: canvas.width, height: canvas.height };
  const ratio = canvas.width / canvas.height;
  return ratio >= 1 ? { width: 1024, height: snap(1024 / ratio) } : { width: snap(1024 * ratio), height: 1024 };
}
function validateGenerationDimensions(input: ImageCreateInput): void {
  for (const [label, value] of [["width", input.width], ["height", input.height]] as const) {
    if (value === undefined) continue;
    if (value < 256 || value > 1024 || value % 8 !== 0)
      throw new ImageCreateError("INVALID_DIMENSIONS", `${label} must be 256..1024 and a multiple of 8 (generation provider bounds)`);
  }
}
function requirePrompt(input: ImageCreateInput): string {
  const prompt = input.prompt?.trim();
  if (!prompt) throw new ImageCreateError("INPUT_INVALID", `action ${input.action} requires prompt`);
  return prompt;
}
function requireOutput(input: ImageCreateInput, required: boolean): { path: string; format: OutputFormat } | null {
  const path = input.outputPath?.trim();
  if (!path) {
    if (required) throw new ImageCreateError("INPUT_INVALID", `action ${input.action} requires outputPath`);
    return null;
  }
  const format = outputFormatOf(path);
  if (!format) throw new ImageCreateError("INPUT_INVALID", `outputPath must end with one of: ${OUTPUT_FORMATS.join("/")}`);
  return { path, format };
}
function publicBaseUrl(deps: ImageCreateDeps): string {
  const raw = deps.publicBaseUrl ?? process.env.ENG_MCP_IMAGE_CREATE_PUBLIC_BASE_URL ?? "https://memoryos-engmcp.2-25-96-245.nip.io";
  return raw.replace(/\/+$/, "");
}

function mapComposeElement(element: ComposeElementInput, index: number): ElementInput {
  if (element.type === "text") {
    if (!element.text) throw new ImageCreateError("INPUT_INVALID", `elements[${index}]: text element requires text`);
    return {
      type: "text",
      text: element.text,
      ...(element.font ? { font: element.font } : {}),
      ...(element.fontSize !== undefined ? { fontSize: element.fontSize } : {}),
      ...(element.color ? { color: element.color } : {}),
      ...(element.position ? { position: element.position } : {})
    };
  }
  if (element.type === "shape") {
    if (!element.shape || !element.position || element.width === undefined || element.height === undefined)
      throw new ImageCreateError("INPUT_INVALID", `elements[${index}]: shape element requires shape, position, width and height`);
    return {
      type: "shape",
      shape: element.shape,
      position: element.position,
      width: element.width,
      height: element.height,
      ...(element.color ? { color: element.color } : {})
    };
  }
  if (!element.path) throw new ImageCreateError("INPUT_INVALID", `elements[${index}]: ${element.type} element requires path`);
  return {
    type: "image",
    path: element.path,
    ...(element.position ? { position: element.position } : {}),
    ...(element.width !== undefined ? { width: element.width } : {}),
    ...(element.height !== undefined ? { height: element.height } : {}),
    ...(element.scale !== undefined ? { scale: element.scale } : {})
  };
}
function productElement(product: { path: string; placement?: PlacementInput }, canvas: { width: number; height: number }): ElementInput {
  const width = product.placement?.width ?? Math.round(canvas.width * 0.5);
  const height = product.placement?.height ?? Math.round(canvas.height * 0.55);
  const position = product.placement?.position ?? { x: Math.round((canvas.width - width) / 2), y: Math.round(canvas.height * 0.24) };
  return {
    type: "image",
    path: product.path,
    position,
    width,
    height,
    ...(product.placement?.scale !== undefined ? { scale: product.placement.scale } : {})
  };
}
function logoElement(logo: { path: string; placement?: PlacementInput }, canvas: { width: number; height: number } | null): ElementInput {
  const width = logo.placement?.width ?? (canvas ? Math.round(canvas.width * 0.16) : undefined);
  const height = logo.placement?.height ?? (canvas ? Math.round(canvas.height * 0.09) : undefined);
  const position = logo.placement?.position ?? (canvas ? { x: Math.round(canvas.width * 0.05), y: Math.round(canvas.height * 0.045) } : { x: 32, y: 32 });
  return {
    type: "image",
    path: logo.path,
    position,
    ...(width !== undefined ? { width } : {}),
    ...(height !== undefined ? { height } : {}),
    ...(logo.placement?.scale !== undefined ? { scale: logo.placement.scale } : {})
  };
}
function textElement(text: string, canvas: { width: number; height: number }, yRatio: number, sizeRatio: number): ElementInput {
  return {
    type: "text",
    text,
    fontSize: Math.max(12, Math.round(canvas.height * sizeRatio)),
    color: "#ffffff",
    position: { x: Math.round(canvas.width * 0.06), y: Math.round(canvas.height * yRatio) }
  };
}

type RunContext = {
  outputs: Record<string, unknown>[];
  generatedAssets: Record<string, unknown>[];
  operationsApplied: string[];
  warnings: string[];
  document: Record<string, unknown> | null;
};
async function generateAndStage(plan: GenerationPlan, deps: ImageCreateDeps, ctx: RunContext): Promise<string> {
  let generation: GenerationResult;
  if (deps.generate) {
    generation = await deps.generate({ prompt: plan.prompt, width: plan.width, height: plan.height, model: plan.model });
  } else {
    const credential = await (deps.credentialLoader ?? resolveGenerationCredential)();
    if (!credential)
      throw new ImageCreateError("GENERATION_PROVIDER_UNAVAILABLE", "no generation credential available (env CLOUDFLARE_API_TOKEN/CLOUDFLARE_ACCOUNT_ID or operator-provisioned credential file); failing closed");
    generation = await generateWithProvider(credential, { prompt: plan.prompt, width: plan.width, height: plan.height, model: plan.model });
  }
  const putAsset = deps.putAsset ?? putGeneratedAsset;
  const assetId = putAsset(generation.bytes, generation.contentType);
  ctx.generatedAssets.push({ index: ctx.generatedAssets.length + 1, contentType: generation.contentType, bytes: generation.bytes.length, provider: "cloudflare-workers-ai", model: generation.model });
  ctx.operationsApplied.push(`generate:${generation.model}`);
  return `${publicBaseUrl(deps)}${IMAGE_ASSET_PATH_PREFIX}${assetId}`;
}
type GenerationPlan = { prompt: string; width?: number; height?: number; model?: string };
async function generateDeliverExport(plan: GenerationPlan, output: { path: string; format: OutputFormat }, composeForEditing: boolean, deps: ImageCreateDeps, ctx: RunContext): Promise<Record<string, unknown>> {
  const assetUrl = await generateAndStage(plan, deps, ctx);
  const opened = await editStep(deps, { action: "document", document: { op: "open", path: assetUrl } }, "open-generated");
  if (!opened.ok) throw mapEditFailure("open-generated", opened);
  ctx.operationsApplied.push("open:generated-asset");
  ctx.document = { opened: true, source: "generated", composedForEditing: composeForEditing };
  const exported = await editStep(deps, { action: "export", output: { path: output.path, format: output.format, overwrite: true } }, "export");
  if (!exported.ok) throw mapEditFailure("export", exported);
  ctx.operationsApplied.push(`export:${output.format}`);
  return exported.result;
}
type Finish = (status: "ok" | "partial" | "error", extra?: Record<string, unknown>) => Record<string, unknown>;

async function runGenerationFamily(input: ImageCreateInput, deps: ImageCreateDeps, ctx: RunContext, finish: Finish): Promise<Record<string, unknown>> {
  if (input.referenceImages && input.referenceImages.length > 0)
    throw new ImageCreateError("UNSUPPORTED_REFERENCE_MODE", "the generation provider has no image-reference mode; referenceImages are not supported by engineering.image.create v1");
  const prompt = requirePrompt(input);
  validateGenerationDimensions(input);
  const output = requireOutput(input, true)!;
  const count = input.action === "variation" ? (input.count ?? 2) : (input.count ?? 1);
  if (input.action === "variation" && count < 2) throw new ImageCreateError("INPUT_INVALID", "variation requires count >= 2");
  for (let index = 1; index <= count; index++) {
    const styleHint = input.action === "variation" ? input.styleHints?.[index - 1] : undefined;
    const composedPrompt = [prompt, styleHint].filter(Boolean).join(", ");
    const finalPrompt = input.action === "background" ? `background only (no subject, no product, no text, no watermark): ${composedPrompt}` : composedPrompt;
    const itemPath = count > 1 ? withOutputIndex(output.path, index) : output.path;
    try {
      const result = await generateDeliverExport({ prompt: finalPrompt, width: input.width, height: input.height, model: input.model }, { path: itemPath, format: output.format }, input.compose === true, deps, ctx);
      const exportInfo = exportOf(result);
      ctx.outputs.push({ index, ok: true, path: itemPath, format: output.format, ...(exportInfo ? { export: exportInfo } : {}) });
    } catch (error) {
      if (count === 1) throw error;
      const code = error instanceof ImageCreateError ? error.code : "GENERATION_FAILED";
      const message = error instanceof Error ? error.message : "generation item failed";
      ctx.outputs.push({ index, ok: false, path: itemPath, code, message });
      ctx.warnings.push(`item ${index} failed with ${code}`);
    }
  }
  const failures = ctx.outputs.filter((item) => item.ok === false);
  if (failures.length === ctx.outputs.length) {
    const first = failures[0] as { code?: string; message?: string } | undefined;
    return finish("error", { code: first?.code ?? "GENERATION_FAILED", message: first?.message ?? "all generation items failed" });
  }
  if (failures.length > 0) return finish("partial", { code: "PARTIAL_GENERATION", message: `${failures.length} of ${ctx.outputs.length} items failed` });
  return finish("ok");
}

async function runProduct(input: ImageCreateInput, deps: ImageCreateDeps, ctx: RunContext, finish: Finish): Promise<Record<string, unknown>> {
  const output = requireOutput(input, true)!;
  if (!input.product) throw new ImageCreateError("INPUT_INVALID", "action product requires product.path");
  validateGenerationDimensions(input);
  const canvas = input.canvas ?? null;
  const scenePrompt = input.prompt?.trim() ?? "";
  let backgroundUrl: string | null = null;
  if (canvas && scenePrompt.length > 0) {
    const size = providerBackgroundSize(canvas);
    backgroundUrl = await generateAndStage({ prompt: scenePrompt, width: size.width, height: size.height, model: input.model }, deps, ctx);
  }
  if (canvas) {
    const created = await editStep(deps, { action: "document", document: { op: "create", width: canvas.width, height: canvas.height } }, "create-document");
    if (!created.ok) throw mapEditFailure("create-document", created);
    ctx.operationsApplied.push("create-document");
    ctx.document = { opened: true, width: canvas.width, height: canvas.height, source: backgroundUrl ? "generated-scene" : "blank" };
  } else {
    const opened = await editStep(deps, { action: "document", document: { op: "open", path: input.product.path } }, "open-input:product");
    if (!opened.ok) throw mapEditFailure("open-input:product", opened);
    ctx.operationsApplied.push("open-input:product");
    ctx.document = { opened: true, source: "product" };
  }
  const elements: ElementInput[] = [];
  if (backgroundUrl && canvas) {
    elements.push({ type: "image", path: backgroundUrl, position: { x: 0, y: 0 }, width: canvas.width, height: canvas.height });
  }
  if (canvas) elements.push(productElement(input.product, canvas));
  if (input.logo) elements.push(logoElement(input.logo, canvas));
  if (elements.length > 0) {
    const composed = await editStep(deps, { action: "compose", elements }, "compose");
    if (!composed.ok) throw mapEditFailure("compose", composed, [input.product.path, input.logo?.path ?? ""]);
    ctx.operationsApplied.push("compose");
  }
  const exported = await editStep(deps, { action: "export", output: { path: output.path, format: output.format, overwrite: true } }, "export");
  if (!exported.ok) throw mapEditFailure("export", exported);
  ctx.operationsApplied.push(`export:${output.format}`);
  const exportInfo = exportOf(exported.result);
  ctx.outputs.push({ index: 1, ok: true, path: output.path, format: output.format, ...(exportInfo ? { export: exportInfo } : {}) });
  return finish("ok");
}

async function runCampaign(input: ImageCreateInput, deps: ImageCreateDeps, ctx: RunContext, finish: Finish): Promise<Record<string, unknown>> {
  if (!input.canvas) throw new ImageCreateError("INPUT_INVALID", "action campaign requires canvas");
  const output = requireOutput(input, true)!;
  validateGenerationDimensions(input);
  const canvas = input.canvas;
  const concept = input.concept?.trim() ?? "";
  const backgroundPrompt = `professional advertising key visual background${concept.length > 0 ? `, ${concept}` : ""}, empty clean stage reserved for product and text, no product, no text, no watermark`;
  const size = providerBackgroundSize(canvas);
  const backgroundUrl = await generateAndStage({ prompt: backgroundPrompt, width: size.width, height: size.height, model: input.model }, deps, ctx);
  const created = await editStep(deps, { action: "document", document: { op: "create", width: canvas.width, height: canvas.height } }, "create-document");
  if (!created.ok) throw mapEditFailure("create-document", created);
  ctx.operationsApplied.push("create-document");
  ctx.document = { opened: true, width: canvas.width, height: canvas.height, source: "generated-background" };
  const elements: ElementInput[] = [{ type: "image", path: backgroundUrl, position: { x: 0, y: 0 }, width: canvas.width, height: canvas.height }];
  if (input.product) elements.push(productElement(input.product, canvas));
  if (input.logo) elements.push(logoElement(input.logo, canvas));
  const headline = input.headline?.trim();
  const subheadline = input.subheadline?.trim();
  const cta = input.cta?.trim();
  if (headline) elements.push(textElement(headline, canvas, 0.775, 0.06));
  if (subheadline) elements.push(textElement(subheadline, canvas, 0.855, 0.035));
  if (cta) elements.push(textElement(cta, canvas, 0.915, 0.03));
  const composed = await editStep(deps, { action: "compose", elements }, "compose");
  if (!composed.ok) throw mapEditFailure("compose", composed, [input.product?.path ?? "", input.logo?.path ?? ""]);
  ctx.operationsApplied.push("compose");
  const exported = await editStep(deps, { action: "export", output: { path: output.path, format: output.format, overwrite: true } }, "export");
  if (!exported.ok) throw mapEditFailure("export", exported);
  ctx.operationsApplied.push(`export:${output.format}`);
  const exportInfo = exportOf(exported.result);
  ctx.outputs.push({ index: 1, ok: true, path: output.path, format: output.format, ...(exportInfo ? { export: exportInfo } : {}) });
  return finish("ok");
}

async function runCompose(input: ImageCreateInput, deps: ImageCreateDeps, ctx: RunContext, finish: Finish): Promise<Record<string, unknown>> {
  if (!input.canvas) throw new ImageCreateError("INPUT_INVALID", "action compose requires canvas");
  const mapped = (input.elements ?? []).map((element, index) => mapComposeElement(element, index));
  if (mapped.length === 0) throw new ImageCreateError("INPUT_INVALID", "action compose requires elements");
  const output = requireOutput(input, false);
  const created = await editStep(deps, { action: "document", document: { op: "create", width: input.canvas.width, height: input.canvas.height } }, "create-document");
  if (!created.ok) throw mapEditFailure("create-document", created);
  ctx.operationsApplied.push("create-document");
  ctx.document = { opened: true, width: input.canvas.width, height: input.canvas.height, layers: mapped.length };
  const composed = await editStep(deps, { action: "compose", elements: mapped }, "compose");
  if (!composed.ok) throw mapEditFailure("compose", composed, input.elements?.map((element) => element.path ?? "") ?? []);
  ctx.operationsApplied.push("compose");
  if (output) {
    const exported = await editStep(deps, { action: "export", output: { path: output.path, format: output.format, overwrite: true } }, "export");
    if (!exported.ok) throw mapEditFailure("export", exported);
    ctx.operationsApplied.push(`export:${output.format}`);
    const exportInfo = exportOf(exported.result);
    ctx.outputs.push({ index: 1, ok: true, path: output.path, format: output.format, ...(exportInfo ? { export: exportInfo } : {}) });
  } else {
    ctx.warnings.push("no outputPath provided: composition stays open as an editable Photopea document (preview not exported)");
  }
  return finish("ok");
}

export async function runImageCreate(toolName: string, input: ImageCreateInput, deps: ImageCreateDeps = {}): Promise<Record<string, unknown>> {
  void toolName;
  const ctx: RunContext = { outputs: [], generatedAssets: [], operationsApplied: [], warnings: [], document: null };
  const finish: Finish = (status, extra = {}) => ({
    status,
    action: input.action,
    outputs: ctx.outputs,
    generatedAssets: ctx.generatedAssets,
    ...(ctx.document ? { document: ctx.document } : {}),
    operationsApplied: ctx.operationsApplied,
    ...(ctx.warnings.length > 0 ? { warnings: ctx.warnings } : {}),
    ...extra
  });
  try {
    switch (input.action) {
      case "generate":
      case "background":
      case "scene":
      case "variation":
        return await runGenerationFamily(input, deps, ctx, finish);
      case "product":
        return await runProduct(input, deps, ctx, finish);
      case "campaign":
        return await runCampaign(input, deps, ctx, finish);
      case "compose":
        return await runCompose(input, deps, ctx, finish);
    }
  } catch (error) {
    if (error instanceof ImageCreateError) return finish("error", { code: error.code, message: error.message });
    return finish("error", { code: "IMAGE_CREATE_FAILED", message: error instanceof Error ? error.message : "unexpected failure" });
  }
}
