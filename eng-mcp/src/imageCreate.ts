// engineering.image.create V1 — ONE supertool for NEW visual creation.
// Separation of concerns (official): engineering.image.create creates pixels/compositions
// that do not exist yet; engineering.image.edit edits/composes material that already exists.
// Generation reuses the PROVEN path: Cloudflare Workers AI REST -> @cf/black-forest-labs/
// flux-1-schnell -> valid image bytes. Composition delegates ALL document/layer/text/export
// work to engineering.image.edit (src/imageEdit.ts) over the EXISTING local relay — this
// tool never implements a second editor, bridge or protocol. Generated bytes are delivered
// to the local Windows executor over THIS server's HTTPS origin at /image-asset/<uuid>
// (short TTL) because the existing Photopea executor resolves sources as URLs or local
// paths only. Fail-closed everywhere. Credentials are resolved from env or an
// operator-provisioned credential file and are NEVER returned, logged or echoed. No raw
// shell/JS/JSON-RPC/toolName/script/URL execution exists anywhere in the schema.
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";
import type { IncomingMessage, ServerResponse } from "node:http";
import * as z from "zod/v4";
import { runImageEdit, type ImageEditInput } from "./imageEdit.ts";

export const IMAGE_ASSET_PATH_PREFIX = "/image-asset/";
const ASSET_TTL_MS = 15 * 60_000;
const GENERATION_TIMEOUT_MS = 90_000;
const DEFAULT_PROVIDER_MODEL = "@cf/black-forest-labs/flux-1-schnell";
const PROVIDER_RUN_URL = "https://api.cloudflare.com/client/v4/accounts/{account}/ai/run/{model}";

export class ImageCreateError extends Error {
  readonly code: string;
  constructor(code: string, message: string) {
    super(message);
    this.code = code;
    this.name = "ImageCreateError";
  }
}

// ---- short-TTL in-memory asset delivery (one random-UUID URL per generated image) ----
type AssetEntry = { bytes: Buffer; contentType: string; expiresAt: number };
const assetStore = new Map<string, AssetEntry>();
function sweepAssets(now: number): void {
  for (const [id, entry] of assetStore) if (entry.expiresAt <= now) assetStore.delete(id);
}
export function putGeneratedAsset(bytes: Buffer, contentType: string, now = Date.now()): string {
  sweepAssets(now);
  const id = randomUUID();
  assetStore.set(id, { bytes, contentType, expiresAt: now + ASSET_TTL_MS });
  return id;
}
export function imageAssetCount(now = Date.now()): number {
  sweepAssets(now);
  return assetStore.size;
}
export type AssetLookup = { handled: true; status: number; contentType?: string; bytes?: Buffer } | { handled: false };
export function serveImageAsset(method: string, url: string | undefined, now = Date.now()): AssetLookup {
  if (method !== "GET") return { handled: false };
  let pathname = "";
  try { pathname = new URL(url ?? "/", "http://localhost").pathname; } catch { return { handled: false }; }
  if (!pathname.startsWith(IMAGE_ASSET_PATH_PREFIX)) return { handled: false };
  const id = pathname.slice(IMAGE_ASSET_PATH_PREFIX.length);
  sweepAssets(now);
  const entry = id.length > 0 ? assetStore.get(id) : undefined;
  if (!entry) return { handled: true, status: 404 };
  return { handled: true, status: 200, contentType: entry.contentType, bytes: entry.bytes };
}
export function handleImageAssetRequest(request: IncomingMessage, response: ServerResponse): boolean {
  const lookup = serveImageAsset(request.method ?? "", request.url);
  if (!lookup.handled) return false;
  if (lookup.status === 200 && lookup.bytes) {
    response.writeHead(200, { "content-type": lookup.contentType ?? "application/octet-stream", "content-length": String(lookup.bytes.length), "cache-control": "no-store" });
    response.end(lookup.bytes);
    return true;
  }
  response.writeHead(404, { "content-type": "application/json" });
  response.end(JSON.stringify({ error: "ASSET_NOT_FOUND_OR_EXPIRED" }));
  return true;
}

// ---- credential resolution (fail-closed; values never logged, never returned in results) ----
export type ImageCreateCredential = { apiToken: string; accountId: string };
export function credentialFilePath(): string {
  return process.env.ENG_MCP_IMAGE_CREATE_CREDENTIAL_FILE ?? "/data/image-create.cloudflare.json";
}
export async function resolveGenerationCredential(overrides: { env?: NodeJS.ProcessEnv; file?: string } = {}): Promise<ImageCreateCredential | null> {
  const env = overrides.env ?? process.env;
  const envToken = env.CLOUDFLARE_API_TOKEN;
  const envAccount = env.CLOUDFLARE_ACCOUNT_ID;
  if (typeof envToken === "string" && envToken.length > 0 && typeof envAccount === "string" && envAccount.length > 0)
    return { apiToken: envToken, accountId: envAccount };
  try {
    const parsed = JSON.parse(await readFile(overrides.file ?? credentialFilePath(), "utf8")) as { apiToken?: unknown; accountId?: unknown };
    if (typeof parsed.apiToken === "string" && parsed.apiToken.length > 0 && typeof parsed.accountId === "string" && parsed.accountId.length > 0)
      return { apiToken: parsed.apiToken, accountId: parsed.accountId };
  } catch { /* missing or invalid credential file => fail-closed at call time */ }
  return null;
}

// ---- proven generation path: Cloudflare Workers AI REST (flux-1-schnell) ----
export type GenerationRequest = { prompt: string; width?: number; height?: number; model?: string };
export type GenerationResult = { bytes: Buffer; contentType: string; model: string };
export async function generateWithProvider(credential: ImageCreateCredential, request: GenerationRequest): Promise<GenerationResult> {
  const model = request.model ?? DEFAULT_PROVIDER_MODEL;
  const url = PROVIDER_RUN_URL.replace("{account}", encodeURIComponent(credential.accountId)).replace("{model}", encodeURIComponent(model));
  const payload: Record<string, unknown> = { prompt: request.prompt, steps: 4 };
  if (request.width !== undefined) payload.width = request.width;
  if (request.height !== undefined) payload.height = request.height;
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), GENERATION_TIMEOUT_MS);
  try {
    const res = await fetch(url, {
      method: "POST",
      headers: { authorization: `Bearer ${credential.apiToken}`, "content-type": "application/json" },
      body: JSON.stringify(payload),
      signal: controller.signal
    });
    if (!res.ok) throw new ImageCreateError("GENERATION_FAILED", `generation provider rejected the request (HTTP ${res.status})`);
    const body = await res.json().catch(() => null) as { result?: { image?: unknown } } | null;
    const encoded = body?.result?.image;
    if (typeof encoded !== "string" || encoded.length < 100) throw new ImageCreateError("GENERATION_FAILED", "generation provider returned no usable image payload");
    const bytes = Buffer.from(encoded, "base64");
    if (bytes.length === 0) throw new ImageCreateError("GENERATION_FAILED", "generation provider image payload could not be decoded");
    return { bytes, contentType: "image/jpeg", model };
  } catch (error) {
    if (error instanceof ImageCreateError) throw error;
    throw new ImageCreateError("GENERATION_FAILED", `generation provider call failed: ${error instanceof Error ? error.message : "unknown failure"}`);
  } finally {
    clearTimeout(timer);
  }
}

